import fs from 'node:fs/promises'
import path from 'node:path'
import { chromium } from 'playwright'

const out = path.dirname(new URL(import.meta.url).pathname).replace(/^\/(\w:)/, '$1')
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1, reducedMotion: 'reduce' })
const page = await context.newPage()
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '처음부터' }).click()
await page.screenshot({ path: path.join(out, 'ui-home.png'), fullPage: true })
await page.locator('.sv-stage').screenshot({ path: path.join(out, 'ui-home-stage.png') })
await page.getByRole('button', { name: '루미와 대화' }).click()
await page.screenshot({ path: path.join(out, 'ui-dialog.png') })
await page.getByRole('button', { name: /밖에 조금 나가볼까 해요/ }).click()
await page.screenshot({ path: path.join(out, 'ui-dialog-choice.png') })
await page.getByRole('button', { name: /동네로 나가기/ }).last().click()
await page.screenshot({ path: path.join(out, 'ui-town.png') })
await page.locator('.sv-stage').screenshot({ path: path.join(out, 'ui-town-stage.png') })
await page.getByRole('button', { name: /공원, 벚꽃길 산책 미션/ }).click()
await page.screenshot({ path: path.join(out, 'ui-park.png') })
await page.getByRole('button', { name: '공원 입구로 이동' }).click()
await page.getByRole('button', { name: '왼쪽으로 이동' }).click()
await page.getByRole('button', { name: '왼쪽으로 이동' }).click()
await page.screenshot({ path: path.join(out, 'ui-reward.png') })
await page.getByRole('button', { name: /내 방에서 보상 보기/ }).click()
await page.screenshot({ path: path.join(out, 'ui-room-reward.png') })
await browser.close()
console.log(out)
