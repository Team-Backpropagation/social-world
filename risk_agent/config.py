def stable_seed(*parts) -> int:
    """프로세스마다 바뀌는 파이썬 hash() 대신 zlib.crc32로 고정 시드를 만든다(재현성 필수 요건)."""
    import zlib
    key = "|".join(str(p) for p in parts).encode("utf-8")
    return (zlib.crc32(key) ^ RNG_SEED) & 0xFFFFFFFF


